def limit_quat(q, max_deg, strength):
    if q.w < 0:
        q = Quaternion([-c for c in q])
    ang = q.angle * strength
    ang = min(ang, radians(max_deg))
    if q.angle < 1e-6:
        return q
    return Quaternion(q.axis, ang)


class Pose:
    def __init__(self):
        self.abs, self.rel, self.off = {}, {}, {}
        self.memo = {}

    def set_abs(self, name, rot3, limit=None):
        self.abs[name] = (rot3, limit)
        self.memo.clear()

    def set_rel(self, name, quat):
        self.rel[name] = quat
        self.memo.clear()

    def set_offset(self, name, vec):
        self.off[name] = vec
        self.memo.clear()

    def pose_of(self, b):
        m = self.memo.get(b.name)
        if m is not None:
            return m
        base = (self.pose_of(b.parent) @ REL[b.name]) if b.parent else b.matrix_local.copy()
        base3 = base.to_3x3()
        quat = None
        if b.name in self.abs:
            rot3, limit = self.abs[b.name]
            quat = (base3.inverted() @ rot3).to_quaternion()
            if limit:
                quat = limit_quat(quat, limit[0], limit[1])
        elif b.name in self.rel:
            quat = self.rel[b.name]
        t = base3.inverted() @ self.off[b.name] if b.name in self.off else Vector((0.0, 0.0, 0.0))
        if quat is None and b.name not in self.off:
            m = base
        else:
            q = quat if quat is not None else Quaternion((1, 0, 0, 0))
            m = base @ Matrix.Translation(t) @ q.to_matrix().to_4x4()
        self.memo[b.name] = m
        return m

    def head(self, name):
        return self.pose_of(bones[name]).translation.copy()

    def result(self, names):
        """local (location, quaternion) of the given bones"""
        self.memo.clear()
        out = {}
        for n in names:
            b = bones[n]
            base = (self.pose_of(b.parent) @ REL[n]) if b.parent else b.matrix_local.copy()
            base3 = base.to_3x3()
            quat = Quaternion((1, 0, 0, 0))
            if n in self.abs:
                rot3, limit = self.abs[n]
                quat = (base3.inverted() @ rot3).to_quaternion()
                if limit:
                    quat = limit_quat(quat, limit[0], limit[1])
            elif n in self.rel:
                quat = self.rel[n]
            t = base3.inverted() @ self.off[n] if n in self.off else Vector((0.0, 0.0, 0.0))
            out[n] = (t, quat)
        return out


def rot_y(a):
    return Matrix.Rotation(radians(a), 3, 'Y')


def rot_x(a):
    return Matrix.Rotation(radians(a), 3, 'X')


def rot_z(a):
    return Matrix.Rotation(radians(a), 3, 'Z')


def body_rot(sway, twist):
    """sway +: lean toward the character's left ; twist +: turn toward the character's left"""
    return rot_z(twist * lateral * -forward) @ rot_y(sway * lateral)


def head_rot(tilt, nod, turn):
    """tilt +: ear to the character's left ; nod +: look down ; turn +: look to the character's left"""
    return rot_z(turn * lateral * -forward) @ rot_x(nod * -forward) @ rot_y(tilt * lateral)


def two_bone(S, T, a, b, pole, fallback):
    d = T - S
    L = d.length
    Lc = min(max(L, abs(a - b) + 1e-3), (a + b) * 0.995)
    u = d.normalized() if L > 1e-6 else Vector((0, 0, -1))
    p = pole - u * pole.dot(u)
    if p.length < 1e-3:
        p = fallback - u * fallback.dot(u)
    p.normalize()
    cosA = (a * a + Lc * Lc - b * b) / (2 * a * Lc)
    sinA = sqrt(max(0.0, 1.0 - cosA * cosA))
    return S + u * (a * cosA) + p * (a * sinA), S + u * Lc


