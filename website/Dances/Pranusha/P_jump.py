# SOLVE ONE FRAME
# ----------------------------------------------------------------------------
HAND_NAMES = []
for s in ("L", "R"):
    HAND_NAMES += [ARM[s]["up"], ARM[s]["fo"], ARM[s]["wr"]]
LEG_NAMES = []
for s in ("L", "R"):
    LEG_NAMES += [LEG[s]["up"], LEG[s]["kn"], LEG[s]["ft"]]
FINGER_NAMES = [n for s in ("L", "R") for chain in FINGERS[s] for n in chain]
KEYED = ["root"] + SPINE + HEAD_CHAIN + HAND_NAMES + (LEG_NAMES if USE_LEGS else []) + FINGER_NAMES


HAND_Y = {}


def solve_frame(i, feet):
    r = rows[i]
    P, _shift = root_pose(i)

    sway, twist = r[33] * TORSO_STRENGTH, r[34] * TORSO_STRENGTH
    tilt, nod, turn = r[30] * HEAD_STRENGTH, r[31] * HEAD_STRENGTH, r[32] * HEAD_STRENGTH
    q_id = Quaternion((1, 0, 0, 0))
    q_t = body_rot(sway, twist).to_quaternion()
    for k, name in enumerate(SPINE):
        P.set_abs(name, q_id.slerp(q_t, (k + 1) / len(SPINE)).to_matrix() @ R3[name])
    q_h = head_rot(tilt, nod, turn).to_quaternion()
    for k, name in enumerate(HEAD_CHAIN):
        P.set_abs(name, q_t.slerp(q_h, (k + 1) / len(HEAD_CHAIN)).to_matrix() @ R3[name])

    # ---- legs
    if USE_LEGS:
        for s in ("L", "R"):
            Lg = LEG[s]
            S = P.head(Lg["up"])
            side = 1.0 if s == "L" else -1.0
            fallback = Vector((SIDE_X[s] * 0.15, forward * 1.0, 0.0))
            E, A = two_bone(S, feet[s][i], Lg["a"], Lg["b"], fallback, fallback)
            P.set_abs(Lg["up"], Lg["vK"].rotation_difference(E - S).to_matrix() @ R3[Lg["up"]])
            P.set_abs(Lg["kn"], Lg["vA"].rotation_difference(A - E).to_matrix() @ R3[Lg["kn"]])
            P.set_abs(Lg["ft"], R3[Lg["ft"]])

    # ---- arms
    SL, SR = P.head(ARM["L"]["up"]), P.head(ARM["R"]["up"])
    Mc = (SL + SR) * 0.5
    targets = {}
    for s in ("L", "R"):
        A = ARM[s]
        arr = r[0:15] if s == "L" else r[15:30]
        sh_m, el_m, wr_m = Vector(arr[0:3]), Vector(arr[3:6]), Vector(arr[6:9])
        S = P.head(A["up"])
        W = Mc + DV(wr_m) * ARM_SCALE
        pole_m = DV(el_m - sh_m)
        u_m = DV(wr_m - sh_m).normalized()
        pole = pole_m - u_m * pole_m.dot(u_m)
        fallback = DV(Vector((0.4 * (1 if s == "L" else -1), -0.4, -1.0)))
        E, Wc = two_bone(S, W, A["a"], A["b"], pole, fallback)
        P.set_abs(A["up"], A["vE"].rotation_difference(E - S).to_matrix() @ R3[A["up"]])
        P.set_abs(A["fo"], A["vW"].rotation_difference(Wc - E).to_matrix() @ R3[A["fo"]])
        hd, sd = DV(Vector(arr[9:12])).normalized(), DV(Vector(arr[12:15]))
        y = (sd - hd * sd.dot(hd))
        # How the hand is twisted comes from the "across the hand" direction. When that direction lines up with
        # the hand direction it cannot be trusted, so the previous twist is kept (this removes the wrist snaps).
        conf = smooth((y.length - 0.2) / 0.4)
        prev = HAND_Y.get(s)
        if y.length > 1e-4:
            y = y.normalized()
        if prev is not None:
            yp = prev - hd * prev.dot(hd)
            if yp.length > 1e-3:
                yp.normalize()
                y = (y * conf + yp * (1.0 - conf)) if y.length > 1e-4 else yp
        if y.length > 1e-4:
            y.normalize()
            HAND_Y[s] = y.copy()
            Fm = Matrix([hd, y, hd.cross(y)]).transposed()
            P.set_abs(A["wr"], (Fm @ A["F"].inverted()) @ R3[A["wr"]], (WRIST_LIMIT, HAND_STRENGTH))
        targets[s] = Wc

    # ---- fingers (fist)
    close = FIST * (1.0 - open_amount(i))
    thumb_close = close * (1.0 - smooth((i - TUCK_AT) / 8.0) * (1.0 - smooth((i - (TUCK_AT + (MOVE_LAST - TUCK_ROW) + 3)) / 8.0)) * 0.9)
    for s in ("L", "R"):
        for fi, chain in enumerate(FINGERS[s]):
            angles = THUMB_CURL if fi == 0 else FINGER_CURL
            for k, name in enumerate(chain):
                if fi == 0 and name in THUMB_TUCK:
                    P.set_rel(name, Quaternion((1.0, 0.0, 0.0, 0.0)).slerp(Quaternion(THUMB_TUCK[name]), thumb_close))
                else:
                    P.set_rel(name, Quaternion(CURL_AXIS[name], radians(angles[k] * close)))

    return P.result(KEYED), targets


